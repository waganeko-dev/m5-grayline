#!/usr/bin/env python3
"""Rasterize Natural Earth land polygons into a 1-bit equirectangular mask.

Usage: python3 tools/gen_landmask.py ne_50m_land.geojson src/landmask.h [W H]

Source data: Natural Earth (public domain),
https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_land.geojson

The mask starts at longitude -180 (column 0) and latitude +90 (row 0).
Each output pixel is land when at least half of its SS x SS sub-samples are land.
"""
import json
import sys
from collections import defaultdict

SS = 4  # supersampling factor per axis


def rings(geojson):
    for feat in geojson["features"]:
        g = feat["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            for ring in poly:
                yield ring


def main():
    src, dst = sys.argv[1], sys.argv[2]
    W = int(sys.argv[3]) if len(sys.argv) > 3 else 320
    H = int(sys.argv[4]) if len(sys.argv) > 4 else 160
    sw, sh = W * SS, H * SS

    with open(src) as f:
        data = json.load(f)

    # Bucket polygon edges by the supersampled rows they cross.
    buckets = defaultdict(list)
    for ring in rings(data):
        for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]):
            if y0 == y1:
                continue
            # convert latitude to row coordinate (row centers at r + 0.5)
            r0 = (90.0 - y0) / 180.0 * sh
            r1 = (90.0 - y1) / 180.0 * sh
            c0 = (x0 + 180.0) / 360.0 * sw
            c1 = (x1 + 180.0) / 360.0 * sw
            lo, hi = min(r0, r1), max(r0, r1)
            for row in range(max(0, int(lo)), min(sh, int(hi) + 1)):
                yc = row + 0.5
                if lo <= yc < hi:
                    buckets[row].append((r0, c0, r1, c1))

    counts = [[0] * W for _ in range(H)]
    for row in range(sh):
        yc = row + 0.5
        xs = sorted(c0 + (yc - r0) / (r1 - r0) * (c1 - c0) for r0, c0, r1, c1 in buckets[row])
        for a, b in zip(xs[0::2], xs[1::2]):
            # sub-sample column centers at k + 0.5 inside [a, b)
            k0 = max(0, int(a - 0.5 + 0.999999))
            k1 = min(sw - 1, int(b - 0.5))
            for k in range(k0, k1 + 1):
                if a <= k + 0.5 < b:
                    counts[row // SS][k // SS] += 1

    thresh = SS * SS // 2
    out = []
    out.append("// Generated by tools/gen_landmask.py from Natural Earth ne_50m_land (public domain).")
    out.append("// 1 bit per pixel, MSB first. Column 0 = longitude -180, row 0 = latitude +90.")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append(f"constexpr int LANDMASK_W = {W};")
    out.append(f"constexpr int LANDMASK_H = {H};")
    out.append(f"static const uint8_t LANDMASK[{H}][{W // 8}] = {{")
    land_px = 0
    for y in range(H):
        bytes_ = []
        for bx in range(W // 8):
            v = 0
            for bit in range(8):
                if counts[y][bx * 8 + bit] >= thresh:
                    v |= 0x80 >> bit
                    land_px += 1
            bytes_.append(f"0x{v:02x}")
        out.append("  {" + ",".join(bytes_) + "},")
    out.append("};")
    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {dst}: {W}x{H}, land {land_px / (W * H):.1%}")

    # ASCII preview (every 4th row / 2nd column) to stderr
    for y in range(0, H, 4):
        sys.stderr.write("".join("#" if counts[y][x] >= thresh else "." for x in range(0, W, 2)) + "\n")


if __name__ == "__main__":
    main()

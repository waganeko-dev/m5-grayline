#!/usr/bin/env python3
"""Convert day / night Earth images into RGB565 arrays for the photo map style.

Usage:
  python3 tools/gen_photomaps.py day.jpg night.jpg src/photomaps.h

Decoding and resizing use Pillow (`pip install pillow`) when it is installed,
otherwise the macOS built-in `sips` command.

Sources (NASA, public domain, via Wikimedia Commons):
  day:   https://commons.wikimedia.org/wiki/File:Whole_world_-_land_and_oceans.jpg
  night: https://commons.wikimedia.org/wiki/File:The_earth_at_night.jpg
Both must be equirectangular with longitude -180 at the left edge.

Tuning baked into the data: the dark Blue Marble ocean is lifted with a
gamma of 0.72, and the city lights are brightened 1.5x.
"""
import os
import struct
import subprocess
import sys
import tempfile

W, H = 320, 160
DAY_GAMMA = 0.72
NIGHT_GAIN = 1.5


def load_bmp(path):
    try:
        from PIL import Image
    except ImportError:
        return load_bmp_sips(path)
    img = Image.open(path).convert("RGB").resize((W, H), Image.LANCZOS)
    px = img.load()
    return [[px[x, y] for x in range(W)] for y in range(H)]


def load_bmp_sips(path):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "img.bmp")
        subprocess.run(["sips", "-s", "format", "bmp", "-z", str(H), str(W), path, "--out", out],
                       check=True, capture_output=True)
        d = open(out, "rb").read()
    off = struct.unpack_from("<I", d, 10)[0]
    w, h = struct.unpack_from("<ii", d, 18)
    assert (w, abs(h)) == (W, H), (w, h)
    stride = (w * 3 + 3) & ~3
    rows = []
    for y in range(H):
        yy = y if h < 0 else H - 1 - y
        r = d[off + yy * stride: off + yy * stride + w * 3]
        rows.append([(r[i * 3 + 2], r[i * 3 + 1], r[i * 3]) for i in range(w)])
    return rows


def rgb565(p):
    r, g, b = (max(0, min(255, int(v))) for v in p)
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)


def emit(name, rows, f):
    f.write(f"static const uint16_t {name}[{H}][{W}] = {{\n")
    for row in rows:
        f.write("  {" + ",".join(f"0x{rgb565(p):04x}" for p in row) + "},\n")
    f.write("};\n")


def main():
    day_path, night_path, dst = sys.argv[1:4]
    day = [[tuple(255 * (v / 255) ** DAY_GAMMA for v in p) for p in row] for row in load_bmp(day_path)]
    night = [[tuple(v * NIGHT_GAIN for v in p) for p in row] for row in load_bmp(night_path)]
    with open(dst, "w") as f:
        f.write("// Generated by tools/gen_photomaps.py from NASA Blue Marble / Earth at Night\n")
        f.write("// (public domain). RGB565, column 0 = longitude -180, row 0 = latitude +90.\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"constexpr int PHOTOMAP_W = {W};\nconstexpr int PHOTOMAP_H = {H};\n")
        emit("PHOTO_DAY", day, f)
        emit("PHOTO_NIGHT", night, f)
    print("wrote", dst)


if __name__ == "__main__":
    main()
